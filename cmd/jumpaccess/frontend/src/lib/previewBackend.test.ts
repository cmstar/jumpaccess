test('预览取消任务停止进度，重试从头完成', async () => {
  vi.useFakeTimers()
  const { previewBackend: backend } = await import('./previewBackend')
  const session = await backend.startSFTPSession({ profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' })
  const [transfer] = await backend.startSFTPTransfer({ sessionId: session.id, direction: 'upload', sources: ['/preview/uploads/release.zip'], destination: session.directory })
  await vi.advanceTimersByTimeAsync(500)
  await backend.cancelSFTPTransfer(transfer.id)
  const [cancelled] = await backend.listSFTPTransfers(session.id)
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(session.id))[0]).toMatchObject({ status: 'cancelled', transferred: cancelled.transferred })
  expect(await backend.retrySFTPTransfer(transfer.id)).toMatchObject({ status: 'queued', transferred: 0 })
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(session.id))[0].status).toBe('completed')
})

test('预览文件夹上传下载保留内容，失败任务保留原因并允许重试', async () => {
  vi.useFakeTimers()
  const { previewBackend: backend } = await import('./previewBackend')
  const session = await backend.startSFTPSession({ profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' })
  await backend.startSFTPTransfer({ sessionId: session.id, direction: 'upload', sources: ['/preview/uploads/release'], destination: session.directory })
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.readSFTPDirectory(session.id, '/home/deploy/release')).entries.map((entry) => entry.name)).toContain('README.md')
  const [download] = await backend.startSFTPTransfer({ sessionId: session.id, direction: 'download', sources: ['/home/deploy/future'], destination: '/preview/downloads' })
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(session.id)).find((entry) => entry.id === download.id)).toMatchObject({ status: 'failed', error: expect.any(String) })
  await backend.makeSFTPDirectory(session.id, '/home/deploy/future')
  await backend.retrySFTPTransfer(download.id)
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(session.id)).find((entry) => entry.id === download.id)?.status).toBe('completed')
})

test('预览覆盖在完成后替换内容，关闭会话只取消自己的传输', async () => {
  vi.useFakeTimers()
  const { previewBackend: backend } = await import('./previewBackend')
  const request = { profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' }
  const first = await backend.startSFTPSession(request)
  const second = await backend.startSFTPSession(request)
  const [overwrite] = await backend.startSFTPTransfer({ sessionId: first.id, direction: 'upload', sources: ['/preview/uploads/notes.txt'], destination: first.directory })
  await vi.advanceTimersByTimeAsync(200)
  await backend.resolveSFTPConflict(overwrite.id, 'overwrite', false)
  expect((await backend.readSFTPDirectory(first.id, first.directory)).entries.find((entry) => entry.name === 'notes.txt')?.size).toBe(1200)
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.readSFTPDirectory(first.id, first.directory)).entries.find((entry) => entry.name === 'notes.txt')?.size).toBe(2000)
  await backend.startSFTPTransfer({ sessionId: first.id, direction: 'upload', sources: ['/preview/uploads/release.zip'], destination: first.directory })
  await backend.startSFTPTransfer({ sessionId: second.id, direction: 'upload', sources: ['/preview/uploads/release'], destination: second.directory })
  await backend.closeSFTPSession(first.id)
  expect((await backend.listSFTPTransfers(first.id))[1].status).toBe('cancelled')
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(second.id))[0].status).toBe('completed')
})
