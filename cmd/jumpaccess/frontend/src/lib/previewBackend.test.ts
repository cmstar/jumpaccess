test('预览 SFTP 会话独立于 SSH，目录候选不可用时回到 home', async () => {
  const { previewBackend } = await import('./previewBackend')
  const request = { profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' }
  const first = await previewBackend.startSFTPSession({ ...request, directory: '/missing' })
  const second = await previewBackend.startSFTPSession(request)
  expect(first.directory).toBe('/home/deploy')
  expect(second.id).not.toBe(first.id)
  const directory = await previewBackend.readSFTPDirectory(first.id, first.directory)
  expect(directory.entries.some((entry) => entry.name === 'projects')).toBe(true)
  await previewBackend.closeSFTPSession(first.id)
  expect((await previewBackend.listSFTPSessions()).find((session) => session.id === second.id)?.status).toBe('active')
})

test('预览支持创建、重命名和删除目录并刷新文件列表', async () => {
  const { previewBackend: backend } = await import('./previewBackend')
  const session = await backend.startSFTPSession({ profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' })
  await backend.makeSFTPDirectory(session.id, '/home/deploy/new')
  await backend.renameSFTPEntry(session.id, '/home/deploy/new', 'renamed')
  expect((await backend.readSFTPDirectory(session.id, '/home/deploy')).entries.map((item) => item.name)).toContain('renamed')
  expect((await backend.readSFTPDirectory(session.id, '/home/deploy/renamed')).entries).toEqual([])
  await backend.removeSFTPEntries(session.id, ['/home/deploy/renamed'])
  expect((await backend.readSFTPDirectory(session.id, '/home/deploy')).entries.map((item) => item.name)).not.toContain('renamed')
})

test('预览文件选择器返回示例路径，上传队列推进后更新远程目录', async () => {
  vi.useFakeTimers()
  const { previewBackend: backend } = await import('./previewBackend')
  const session = await backend.startSFTPSession({ profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' })
  const files = await backend.chooseSFTPUploadFiles()
  expect(files).toEqual(['/preview/uploads/notes.txt', '/preview/uploads/release.zip'])
  expect(await backend.chooseSFTPUploadDirectory()).toBe('/preview/uploads/release')
  expect(await backend.chooseSFTPDownloadDirectory()).toBe('/preview/downloads')
  const states: string[] = []
  const unsubscribe = backend.onSFTPTransfer((transfer) => states.push(transfer.status))
  const queued = await backend.startSFTPTransfer({ sessionId: session.id, direction: 'upload', sources: [files[1]], destination: session.directory })
  expect(queued[0].status).toBe('queued')
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.listSFTPTransfers(session.id))[0]).toMatchObject({ status: 'completed', transferred: 640_000, total: 640_000 })
  expect((await backend.readSFTPDirectory(session.id, session.directory)).entries).toContainEqual(expect.objectContaining({ name: 'release.zip', size: 640_000 }))
  expect(states).toContain('running')
  expect(states).toContain('completed')
  unsubscribe()
})

test('预览同名冲突保留两者时生成新名称并保留原文件', async () => {
  vi.useFakeTimers()
  const { previewBackend: backend } = await import('./previewBackend')
  const session = await backend.startSFTPSession({ profile: 'production', organization: 'org-dev', target: '7f3c91bd', account: 'account-deploy' })
  const [transfer] = await backend.startSFTPTransfer({ sessionId: session.id, direction: 'upload', sources: ['/preview/uploads/notes.txt'], destination: session.directory })
  await vi.advanceTimersByTimeAsync(200)
  expect((await backend.listSFTPTransfers(session.id))[0]).toMatchObject({ status: 'conflict', conflict: { destination: '/home/deploy/notes.txt' } })
  await backend.resolveSFTPConflict(transfer.id, 'keep-both', false)
  await vi.advanceTimersByTimeAsync(2_000)
  expect((await backend.readSFTPDirectory(session.id, session.directory)).entries.map((entry) => entry.name)).toEqual(expect.arrayContaining(['notes.txt', 'notes (1).txt']))
  expect((await backend.listSFTPTransfers(session.id))[0].status).toBe('completed')
})

